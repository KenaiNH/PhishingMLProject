
import hashlib
import json
import pickle
import re
import string
from pathlib import Path

from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.model_selection import StratifiedKFold
from sklearn.pipeline import Pipeline

ROOT = Path(__file__).resolve().parent
SEED = 42
LABELS = {'legitimate': 0, 'phishing': 1}
SCORING = ['accuracy', 'precision', 'recall', 'f1']


def clean_text(text):
    text = str(text).lower()
    text = re.sub(r'http\S+|www\S+', '', text)
    text = re.sub(r'<.*?>', '', text)
    text = re.sub(f'[{re.escape(string.punctuation)}]', '', text)
    text = re.sub(r'\d+', '', text)
    return ' '.join(text.split())


def text_key(text):
    return hashlib.sha256(clean_text(text).encode('utf-8')).hexdigest()


def make_pipeline(classifier):

    return Pipeline([
        ('tfidf', TfidfVectorizer(max_features=5000,
                                 preprocessor=clean_text, lowercase=False)),
        ('classifier', classifier),
    ])


def cv_splitter():
    return StratifiedKFold(n_splits=5, shuffle=True, random_state=SEED)


def save_json(name, data):
    (ROOT / name).write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding='utf-8')


def save_pickle(name, value):
    with (ROOT / name).open('wb') as stream:
        pickle.dump(value, stream, protocol=pickle.HIGHEST_PROTOCOL)


def load_pickle(name):
    # Local artifacts generated by this project only.
    with (ROOT / name).open('rb') as stream:
        return pickle.load(stream)


def cv_summary(results):
    return {metric: {'mean': float(results['test_' + metric].mean()),
                     'std': float(results['test_' + metric].std()),
                     'folds': results['test_' + metric].tolist()}
            for metric in SCORING}
